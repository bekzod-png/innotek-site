export function t(lang, key) {
  const l = isLang(lang) ? lang : DEFAULT_LANG;
  return dict[l][key] ?? dict[DEFAULT_LANG][key] ?? key;
}

// Pick a localized field from a multilingual content object like { uz, ru, en },
// falling back to Uzbek, then to whichever language has content.
export function pick(field, lang) {
  if (!field) return "";
  if (typeof field === "string") return field;
  const l = isLang(lang) ? lang : DEFAULT_LANG;
  return field[l] || field[DEFAULT_LANG] || field.ru || field.en || "";
}
